// npm run icons: vendors the Lucide UI icons (lucide-static, ISC, CREDITS.md) into public/js/icons.js.
// Only the names in NAMES are copied (their inner SVG markup); the client helper DuelIcons draws them with one
// stroke (2), round caps and currentColor, so the --ui-* tokens color them. Add a name here, run it, use it.
const fs = require('fs');
const path = require('path');

const NAMES = [
  'x', 'info', 'flag', 'settings', 'volume-2', 'volume-x', 'check', 'chevron-left', 'chevron-right', 'chevron-down',
  'chevron-up', 'copy', 'link', 'share-2', 'circle-question-mark', 'refresh-cw', 'rotate-ccw', 'lock', 'user', 'play',
  'book-open', 'circle-check', 'smartphone', 'dices', 'shield', 'crosshair', 'target', 'swords', 'bot', 'users',
];

const pkgDir = path.dirname(require.resolve('lucide-static/package.json'));
const { version } = require(path.join(pkgDir, 'package.json'));
const license = fs.readFileSync(path.join(pkgDir, 'LICENSE'), 'utf8').trim();
const icons = {};
const OWN = {};
for (const name of NAMES) {
  if (OWN[name]) { icons[name] = OWN[name]; continue; }
  const src = fs.readFileSync(path.join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = src.slice(src.indexOf('>', src.indexOf('<svg')) + 1, src.lastIndexOf('</svg>'));
  icons[name] = inner.replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>').trim();
}
for (const name of NAMES) if (/fill="(?!none)|stroke="(?!currentColor)/.test(icons[name])) throw new Error(`${name}: an icon with its own color`);

const out = `// Generated by tools/build-icons.js (npm run icons). Do not edit by hand.
// UI icons: Lucide v${version} (lucide-static, https://lucide.dev), ISC license (see CREDITS.md).
//
// DuelIcons.svg(name, { size, label, cls, stroke }) -> an <svg> string: viewBox 24, stroke 2, round caps and joins,
//   fill none, stroke currentColor (CSS colors it with the tokens). aria-hidden unless a label is given (then role="img").
//   No size = CSS sizes it (.vi is 1.2em; the component rules set their own).
// DuelIcons.el(name, opts) -> the same as an element. DuelIcons.has(name), DuelIcons.names.
// DuelIcons.fill(root): every [data-icon="<name>"] inside root (and root itself) gets its icon. Static markup is
//   filled at startup and markup added later is filled by a MutationObserver; call fill() yourself if you need the
//   icon in the same tick (e.g. to measure it).
//
${license.split('\n').map((l) => ('// ' + l).trimEnd()).join('\n')}
(function () {
  'use strict';
  const ICONS = ${JSON.stringify(icons, null, 2).replace(/\n/g, '\n  ')};
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  function svg(name, opts = {}) {
    const body = ICONS[name];
    if (body == null) { console.warn('DuelIcons: unknown icon', name); return ''; }
    const size = opts.size ? \` width="\${+opts.size}" height="\${+opts.size}"\` : '';
    const a11y = opts.label ? \`role="img" aria-label="\${esc(opts.label)}"\` : 'aria-hidden="true"';
    const cls = 'vi vi-' + name + (opts.cls ? ' ' + opts.cls : '');
    return \`<svg class="\${esc(cls)}" viewBox="0 0 24 24"\${size} fill="none" stroke="currentColor" stroke-width="\${+opts.stroke || 2}" stroke-linecap="round" stroke-linejoin="round" \${a11y} focusable="false">\${body}</svg>\`;
  }
  function el(name, opts) {
    const t = document.createElement('template');
    t.innerHTML = svg(name, opts);
    return t.content.firstElementChild;
  }
  function fillOne(node) {
    const name = node.getAttribute('data-icon');
    if (!name || node.getAttribute('data-icon-done') === name) return;
    const label = node.getAttribute('data-icon-label');
    node.innerHTML = svg(name, label ? { label } : {});
    node.setAttribute('data-icon-done', name);
  }
  function fill(root = document) {
    if (!root || !root.querySelectorAll) return;
    if (root.nodeType === 1 && root.hasAttribute('data-icon')) fillOne(root);
    root.querySelectorAll('[data-icon]').forEach(fillOne);
  }
  function start() {
    fill(document);
    new MutationObserver((list) => {
      for (const m of list) {
        if (m.type === 'attributes') fillOne(m.target);
        else m.addedNodes.forEach((n) => { if (n.nodeType === 1) fill(n); });
      }
    }).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-icon'] });
  }
  window.DuelIcons = { svg, el, fill, has: (n) => n in ICONS, names: Object.keys(ICONS) };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, { once: true });
  else start();
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'icons.js'), out);
console.log(`public/js/icons.js: ${NAMES.length - Object.keys(OWN).length} Lucide icons (v${version})`);
